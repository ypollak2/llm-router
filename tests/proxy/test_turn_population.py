def test_a_notification_only_turn_is_not_classified_as_a_new_prompt():
    body = _body("refactor the parser module", [NOTIFICATION, REMINDER], main=True)
    assert steps.tier_text(body) == "refactor the parser module"
    assert steps.newest_human_text(body) == "refactor the parser module"


async def test_the_tier_policy_classifies_the_prompt_before_a_notification():
    seen: list[str] = []

    async def classify(text):
        seen.append(text)
        return {"task_type": "query", "complexity": "simple", "chain_head": [], "model": None}

    policy = pt.ClaudeTierPolicy.load()
    body = _body("what is a mutex?", "and a semaphore?", [NOTIFICATION, REMINDER], main=True)
    assert body["model"] not in policy.pinned   # a pinned model would never reach the classifier
    await policy.decide(body, "s-tf1", Stickiness(), classify=classify)
    assert seen == ["and a semaphore?"]


# ── the ledger row ───────────────────────────────────────────────────────────

async def test_every_ledger_row_carries_the_text_free_turn_fields(tmp_path, monkeypatch):
    async def choose(text, pinned, *, anthropic=False):
        return {"task_type": "query", "complexity": "simple", "chain_head": [], "model": None}
    monkeypatch.setattr(pb, "tier_classify", choose)
    app = _app(tmp_path, Upstream())
    sub = _body("Investigate the parser.", f"{MARKER} also check the lexer", main=False)
    main = _body("what is a mutex?", f"and a semaphore? {MARKER}", main=True)
    note = _body("run the tests", NOTIFICATION, main=True)
    for b in (sub, main, note):
        b["metadata"] = {"user_id": json.dumps({"session_id": "s-tf1"})}
        assert (await _post(app, b)).status_code == 200
    rows = _rows(tmp_path)
    got = [(r["step_class"], r["is_main_thread"], r["is_first_call"], r["turn_origin"], r["tier_text_len"])
           for r in rows]
    assert got == [
        ("subagent_turn", False, False, "subagent_brief", len(f"{MARKER} also check the lexer")),
        ("turn_first", True, False, "typed", len(f"and a semaphore? {MARKER}")),
        ("harness_turn", True, False, "task_notification", len("run the tests")),
    ]
    raw = (tmp_path / "proxy_calls.jsonl").read_text()
    assert MARKER not in raw and "lexer" not in raw and "semaphore" not in raw

"""TURNFIRST-1: which population a ``turn_first`` row is measured on.

``steps.step_kind`` called every non-first, non-continuation call ``turn_first``, so a
sub-agent's SendMessage resume and a ``<task-notification>`` turn were counted as human
turns: in the live ledger (2026-10-08 17:50 to 10-09 21:05) all 113 classified turn_first
rows were Sonnet sub-agent calls and 108 of them (95.6%) were classed ``code``. And
``steps._human_text`` stripped only ``<system-reminder>`` blocks, non-greedily, so harness
tags read as typed text and a literal close tag quoted inside a reminder leaked the rest of
the reminder. Synthetic text only; no prompt from any real session.
"""

@pytest.mark.parametrize("name,body,kind,origin,main,first", CASES, ids=[c[0] for c in CASES])
def test_kind_origin_and_flags_tell_the_populations_apart(name, body, kind, origin, main, first):
    assert steps.step_kind(body) == kind
    assert steps.turn_origin(body) == origin
    fields = steps.turn_fields(body)
    assert (fields["is_main_thread"], fields["is_first_call"], fields["turn_origin"]) == (main, first, origin)
    assert fields["tier_text_len"] == len(steps.tier_text(body))


def test_continuations_and_side_calls_have_no_origin():
    cont = _body("read a file", main=True)
    cont["messages"] += [{"role": "assistant", "content": [{"type": "tool_use", "id": "t1", "name": "Read",
                                                            "input": {}}]},
                         {"role": "user", "content": [{"type": "tool_result", "tool_use_id": "t1",
                                                       "content": "x"}]}]
    assert steps.step_kind(cont) == steps.STEP_CONTINUATION and steps.turn_origin(cont) is None
    side = dict(_body("title this", main=True), tools=[])
    assert steps.step_kind(side) == steps.STEP_SIDE_CALL and steps.turn_origin(side) is None
    assert set(steps.TURN_ORIGINS) == {"typed", "subagent_brief", "task_notification", "command", "other_tag"}


# ── _human_text ──────────────────────────────────────────────────────────────

@pytest.mark.parametrize("tag", HARNESS_TAGS)
def test_every_shared_harness_tag_is_stripped(tag):
    name = tag if tag != "local-command" else "local-command-caveat"
    text = f"<{name}>\n{MARKER} injected\n</{name}>\nplease fix the parser"
    assert steps._human_text([{"type": "text", "text": text}]) == "please fix the parser"
    one_line = f"<{name}>{MARKER}</{name}>"
    assert steps._human_text([{"type": "text", "text": one_line}, {"type": "text", "text": "go"}]) == "go"


def test_a_literal_close_tag_inside_a_reminder_does_not_leak_the_rest():
    reminder = ("<system-reminder>\nCLAUDE.md: the strip handles <system-reminder>...</system-reminder> "
                f"blocks; also a stray `</system-reminder>` here.\n{MARKER} private rule text\n"
                "</system-reminder>")
    content = [{"type": "text", "text": reminder}, {"type": "text", "text": "what is a mutex?"}]
    assert steps._human_text(content) == "what is a mutex?"
    # the same reminder inside the typed block itself
    assert steps._human_text(f"{reminder}\nwhat is a mutex?") == "what is a mutex?"


def test_a_tag_named_inside_a_typed_sentence_is_kept():
    typed = "why does the strip only handle <system-reminder> and not <task-notification>?"
    assert steps._human_text([{"type": "text", "text": typed}]) == typed
    body = _body("hi", typed, main=True)
    assert steps.step_kind(body) == steps.STEP_TURN_FIRST and steps.turn_origin(body) == steps.ORIGIN_TYPED


def test_random_reminders_with_literal_close_tags_never_leak():
    """300 synthetic user turns: a reminder whose body quotes the close tag mid-line, then the
    typed prompt. The old non-greedy pattern leaked part of the reminder into the human text."""
    rng = random.Random(7)
    leaks_before = 0
    for i in range(300):
        quote = rng.choice(["`</system-reminder>`", "(</system-reminder>)", "x</system-reminder>y", "plain"])
        reminder = f"<system-reminder>\nline one {quote} more\n{MARKER}-{i}\n</system-reminder>"
        typed = f"question number {i}"
        content = [{"type": "text", "text": reminder}, {"type": "text", "text": typed}]
        assert steps._human_text(content) == typed
        old = re.sub(r"<system-reminder>.*?</system-reminder>", "", steps._text_of(content), flags=re.S).strip()
        leaks_before += MARKER in old
    assert leaks_before > 150   # the fixture does exercise the leak


